# ---------------------------------------------------------------------------
# URL.build: a port is a port, 0 included
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("mode", ["whatwg", "rfc"])
@pytest.mark.parametrize("encoded", [False, True])
@pytest.mark.parametrize("scheme", ["http", "sc"])
def test_build_with_port_zero_without_host(scheme: str, encoded: bool, mode: str) -> None:
    with pytest.raises(ValueError):
        URL.build(scheme=scheme, port=0, encoded=encoded, mode=mode)


@pytest.mark.parametrize("mode", ["whatwg", "rfc"])
def test_build_with_port_81_without_host_unchanged(mode: str) -> None:
    with pytest.raises(ValueError):
        URL.build(scheme="http", port=81, mode=mode)


def test_build_with_host_and_port_zero() -> None:
    u = URL.build(scheme="http", host="example.com", port=0)
    assert str(u) == "http://example.com:0"
    assert u.port == 0


def test_build_without_port_unchanged() -> None:
    assert str(URL.build(scheme="http", host="example.com")) == "http://example.com"
